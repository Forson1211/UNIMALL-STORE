import { test } from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { createApp } from '../app.mjs';
import { configuration } from '../config.mjs';
import { fixture } from './fixtures.mjs';

test('HTTP auth uses private cookies, enforces origin, and consumes recovery tokens once', async t => {
  const f = fixture(); const config = configuration({}); const mail = [];
  const server = createApp({ ...f, config: { ...config, smtpUrl: 'configured', mailFrom: 'test@example.com' }, sendMail: async message => mail.push(message) }).listen(0, '127.0.0.1');
  await once(server, 'listening');
  t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}/api`;
  const post = (path, body, cookie, origin = config.origin) => fetch(base + path, { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json', ...(cookie ? { Cookie: cookie } : {}) }, body: JSON.stringify(body) });
  assert.equal((await post('/auth/signup', {}, null, 'https://evil.example')).status, 403);
  assert.equal((await post('/query', { table: 'profiles' })).status, 401);
  const signup = await post('/auth/signup', { email: 'buyer@example.com', password: 'original-password', options: { data: { role: 'buyer', full_name: 'Campus Buyer' } } });
  assert.equal(signup.status, 201);
  assert.equal((await signup.json()).user.password_hash, undefined);
  const login = await post('/auth/login', { email: 'buyer@example.com', password: 'original-password' });
  assert.equal(login.status, 200);
  const header = login.headers.get('set-cookie');
  assert.match(header, /HttpOnly/i); assert.match(header, /SameSite=Lax/i);
  const cookie = header.split(';')[0];
  const raw = cookie.split('=')[1];
  assert.notEqual(f.rows('sessions')[0].token_hash, raw);
  assert.equal((await fetch(base + '/auth/user', { headers: { Cookie: cookie } })).status, 200);
  assert.equal((await post('/auth/recovery', { email: 'buyer@example.com' })).status, 200);
  const recovery = new URL(mail[0].body.split('\n')[1]);
  const token = new URLSearchParams(recovery.hash.slice(1)).get('token');
  assert.ok(token);
  assert.equal((await post('/auth/reset', { token, password: 'replacement-password' })).status, 200);
  assert.equal((await post('/auth/reset', { token, password: 'replacement-password' })).status, 400);
  assert.equal((await fetch(base + '/auth/user', { headers: { Cookie: cookie } })).status, 401);
  assert.equal((await post('/auth/login', { email: 'buyer@example.com', password: 'original-password' })).status, 401);
  assert.equal((await post('/auth/login', { email: 'buyer@example.com', password: 'replacement-password' })).status, 200);
  const invalid = await fetch(base + '/query', { method: 'POST', headers: { Origin: config.origin, 'Content-Type': 'application/json' }, body: '{' });
  assert.equal(invalid.status, 400);
  assert.equal((await invalid.json()).error.message, 'Invalid JSON request.');
});

test('signup survives email delivery failure and supports resending verification', async t => {
  const f = fixture(); const config = { ...configuration({}), smtpUrl: 'configured', mailFrom: 'test@example.com', requireEmailVerification: true };
  let failMail = true; const mail = [];
  const server = createApp({ ...f, config, sendMail: async message => { if (failMail) throw new Error('Mail unavailable'); mail.push(message); } }).listen(0, '127.0.0.1');
  await once(server, 'listening'); t.after(() => new Promise(resolve => server.close(resolve)));
  const base = 'http://127.0.0.1:' + server.address().port + '/api/auth';
  const post = (path, data) => fetch(base + path, { method: 'POST', headers: { Origin: config.origin, 'Content-Type': 'application/json' }, body: JSON.stringify(data) });
  const values = { email: 'vendor@example.com', password: 'vendor-password', options: { data: { role: 'vendor', full_name: 'Campus Seller', store_name: 'Campus Store' } } };
  const signup = await post('/signup', values);
  assert.equal(signup.status, 201); assert.equal((await signup.json()).verificationEmailSent, false);
  assert.equal(f.rows('users').length, 1);
  assert.equal((await post('/login', values)).status, 403);
  failMail = false;
  assert.equal((await post('/resend-verification', { email: values.email })).status, 200);
  assert.equal(mail.length, 1);
  const link = new URL(mail[0].body.split('\n')[1]);
  const token = new URLSearchParams(link.hash.slice(1)).get('verify');
  assert.equal((await post('/verify', { token })).status, 200);
  assert.equal((await post('/verify', { token })).status, 400);
  assert.equal((await post('/login', values)).status, 200);
});
